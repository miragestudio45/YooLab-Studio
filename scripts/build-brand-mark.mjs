/**
 * Generates `app/components/BrandMark.tsx` from the official brand vectors in
 * `public/brand/`.
 *
 * The component this replaced was TRACED from a 60 px bitmap — marching squares
 * over an upsampled alpha channel — because at the time the only copy of the
 * mark in the repository was a product screenshot. It was rejected for the same
 * reason the hand-drawn editor icons were: a mark redrawn from a thumbnail is a
 * different mark, and the wordmark beside it was Plus Jakarta Sans at 700
 * standing in for letterforms that are actually drawn.
 *
 * Both are now the real files. Run this after re-exporting either SVG; never
 * hand-edit the component.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const paths = (svg) => [...svg.matchAll(/<path\s+d="([^"]+)"[^>]*?(?:fill="([^"]*)")?[^>]*\/>/g)]
  .map((m) => ({ d: m[1], fill: m[2] ?? null }));

const logo = read('public/brand/yoolab-logo.svg');
const icon = read('public/brand/yoolab-icon.svg');

const logoPaths = paths(logo);
// The lockup is drawn mark-first: the four glyph shapes, then the wordmark.
const GLYPH = logoPaths.slice(0, 4).map((p) => p.d);
const WORD = logoPaths.slice(4).map((p) => p.d);

// The plate is the app icon exactly as delivered: rounded tile, its own darker
// gradient (#195658 -> #278681, which is NOT the brand sweep), white mark and
// white wordmark under it.
const iconPaths = paths(icon);
const PLATE = iconPaths[0].d;
const PLATE_MARK = iconPaths.slice(1).map((p) => p.d);
const grad = [...icon.matchAll(/<stop\s+(?:offset="([^"]*)"\s+)?stop-color="([^"]*)"/g)]
  .map((m) => ({ offset: m[1] ?? '0', color: m[2] }));

const esc = (a) => a.map((d) => `  '${d}',`).join('\n');

writeFileSync(new URL('../app/components/BrandMark.tsx', import.meta.url), `/**
 * The official YooLab marks. GENERATED by \`scripts/build-brand-mark.mjs\` from
 * \`public/brand/yoolab-logo.svg\` and \`public/brand/yoolab-icon.svg\`.
 * Re-run the script after re-exporting either file; do not hand-edit this one.
 *
 * Three things ship here and they are not interchangeable:
 *
 *   BrandLockup the horizontal lockup — mark plus the DRAWN wordmark. This is
 *               what the header and footer use. The wordmark is artwork, not
 *               Plus Jakarta Sans at 700, and setting it in a font is the bug
 *               this file exists to stop.
 *   BrandMark   the mark alone, in \`currentColor\`.
 *   BrandPlate  the app icon: rounded tile, the LOGO's own gradient
 *               (#195658 -> #278681) and the mark reversed out in white. That
 *               ramp is the logo's and is deliberately not the brand sweep
 *               (#96DEDA -> #50C9C3) — the tile has to hold white.
 */

/** Mark only. Tight box around the four glyph shapes of the lockup. */
const GLYPH_PATHS = [
${esc(GLYPH)}
];

/** The drawn wordmark, positioned as it sits in the lockup. */
const WORD_PATHS = [
${esc(WORD)}
];

/** The app-icon tile and the mark reversed out of it. */
const PLATE_PATH = '${PLATE}';
const PLATE_MARK_PATHS = [
${esc(PLATE_MARK)}
];

type MarkProps = { size?: number; className?: string; title?: string };

/**
 * The mark on its own, inheriting \`color\`.
 *
 * \`viewBox\` is the mark's own bounds inside the 111x24 lockup, so the glyph
 * fills the box it is given instead of carrying the wordmark's empty width.
 */
export function BrandMark({ size = 24, className, title = 'YooLab' }: MarkProps) {
  return (
    <svg
      className={className}
      width={(size * 29.67) / 23.61}
      height={size}
      viewBox="0 0 29.67 23.61"
      role="img"
      aria-label={title}
      focusable="false"
      fill="currentColor"
    >
      {GLYPH_PATHS.map((d) => <path key={d.slice(0, 16)} d={d} />)}
    </svg>
  );
}

type LogoProps = { height?: number; className?: string; title?: string };

/**
 * The horizontal lockup. Sized by HEIGHT, because that is the dimension a
 * header row actually constrains; the width follows from the artwork's own
 * 111:24 ratio rather than from a second guess.
 */
export function BrandLockup({ height = 24, className, title = 'YooLab' }: LogoProps) {
  return (
    <svg
      className={className}
      width={(height * 110.57) / 24}
      height={height}
      viewBox="0 0 110.57 24"
      role="img"
      aria-label={title}
      focusable="false"
      fill="currentColor"
    >
      {GLYPH_PATHS.map((d) => <path key={d.slice(0, 16)} d={d} />)}
      {WORD_PATHS.map((d) => <path key={d.slice(0, 16)} d={d} />)}
    </svg>
  );
}

/** Older name for the lockup, kept so no call site has to change. */
export const BrandLogo = BrandLockup;

/**
 * The app icon, at whatever size: the delivered tile exactly as drawn —
 * rounded plate, the LOGO's own darker ramp, and the mark AND wordmark
 * reversed out in white. That ramp is not the brand sweep on purpose; a tile
 * this small has to hold white type, and #96DEDA -> #50C9C3 cannot.
 */

export function BrandPlate({ size = 42, className, title = 'YooLab' }: MarkProps) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 60 60"
      role="img"
      aria-label={title}
      focusable="false"
    >
      <defs>
        <linearGradient id="yoolab-plate" x1="0.3" y1="30.12" x2="60.49" y2="30.12" gradientUnits="userSpaceOnUse">
${grad.map((g) => `          <stop offset="${g.offset}" stopColor="${g.color}" />`).join('\n')}
        </linearGradient>
      </defs>
      <path d={PLATE_PATH} fill="url(#yoolab-plate)" />
      {PLATE_MARK_PATHS.map((d) => <path key={d.slice(0, 16)} d={d} fill="#fff" />)}
    </svg>
  );
}
`);
console.log('BrandMark.tsx generated:', GLYPH.length, 'glyph +', WORD.length, 'wordmark +', PLATE_MARK.length, 'plate paths,', grad.length, 'gradient stops');
